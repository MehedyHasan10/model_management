"use client";

import { useEffect, useState, type FormEvent } from "react";
import { createPortal } from "react-dom";
import { Loader2, X, Save } from "lucide-react";
import type { Supplier, SupplierInput } from "@/lib/suppliers";
import { SupplierApiError, suppliersApi } from "@/lib/suppliers";
import toast from "react-hot-toast";

type EditableKey = "name" | "contactPerson" | "phone" | "email" | "address";

const fields: {
  key: EditableKey;
  label: string;
  required?: boolean;
  max: number;
}[] = [
  {
    key: "name",
    label: "Supplier Name",
    required: true,
    max: 200,
  },
  {
    key: "contactPerson",
    label: "Contact Person",
    max: 150,
  },
  {
    key: "phone",
    label: "Phone",
    max: 50,
  },
  {
    key: "email",
    label: "Email",
    max: 254,
  },
  {
    key: "address",
    label: "Address",
    max: 1000,
  },
];

type Props = {
  supplier: Supplier | null;
  onClose: () => void;
  onSaved: () => void;
};

export default function SupplierForm({ supplier, onClose, onSaved }: Props) {
  const [mounted, setMounted] = useState(false);

  const [form, setForm] = useState({
    name: supplier?.name ?? "",
    contactPerson: supplier?.contactPerson ?? "",
    phone: supplier?.phone ?? "",
    email: supplier?.email ?? "",
    address: supplier?.address ?? "",
    notes: supplier?.notes ?? "",
    status: supplier?.status ?? "ACTIVE",
  });

  const [busy, setBusy] = useState(false);

  const [errors, setErrors] = useState<Record<string, string[]>>({});

  useEffect(() => {
    setMounted(true);
  }, []);

  useEffect(() => {
    const onKey = (e: KeyboardEvent) => {
      if (e.key === "Escape" && !busy) {
        onClose();
      }
    };

    document.addEventListener("keydown", onKey);

    return () => {
      document.removeEventListener("keydown", onKey);
    };
  }, [busy, onClose]);

  useEffect(() => {
    const previousOverflow = document.body.style.overflow;
    document.body.style.overflow = "hidden";

    return () => {
      document.body.style.overflow = previousOverflow;
    };
  }, []);

  const change = (key: keyof typeof form, value: string) => {
    setForm((prev) => ({
      ...prev,
      [key]: value,
    }));
  };

  async function submit(e: FormEvent<HTMLFormElement>) {
    e.preventDefault();

    if (!form.name.trim() || busy) return;

    setBusy(true);
    setErrors({});

    try {
      // Supplier code is generated by the backend.
      const payload = {
        ...form,
        name: form.name.trim(),
      };

      if (supplier) {
        await suppliersApi.update(supplier.id, payload as SupplierInput);
      } else {
        await suppliersApi.create(payload as SupplierInput);
      }

      toast.success(supplier ? "Supplier updated" : "Supplier created");

      onSaved();
    } catch (err) {
      if (err instanceof SupplierApiError) {
        setErrors(err.fieldErrors);
      }

      toast.error(err instanceof Error ? err.message : "Save failed");
    } finally {
      setBusy(false);
    }
  }

  if (!mounted) return null;

  return createPortal(
    <div
      className="fixed inset-0 z-[9999] flex items-center justify-center overflow-y-auto bg-slate-950/60 p-4"
      role="presentation"
      onMouseDown={(e) => {
        if (e.target === e.currentTarget && !busy) {
          onClose();
        }
      }}
    >
      <section
        role="dialog"
        aria-modal="true"
        aria-label={supplier ? "Edit supplier" : "Create supplier"}
        className="my-auto max-h-[calc(100dvh-2rem)] w-full max-w-2xl overflow-y-auto rounded-3xl bg-white p-6 shadow-2xl"
      >
        <div className="flex items-start justify-between gap-4">
          <div>
            <h2 className="text-xl font-bold text-slate-900">
              {supplier ? "Edit Supplier" : "Create Supplier"}
            </h2>

            <p className="mt-1 text-sm text-slate-500">
              Manage supplier information.
            </p>
          </div>

          <button
            type="button"
            disabled={busy}
            onClick={onClose}
            aria-label="Close"
            className="rounded-lg p-2 text-slate-500 hover:bg-slate-100 disabled:opacity-50"
          >
            <X size={20} />
          </button>
        </div>

        <form onSubmit={submit} className="mt-6">
          <div className="grid gap-4 sm:grid-cols-2">
            {fields.map(({ key, label, required, max }) => (
              <label
                key={key}
                className="block text-sm font-semibold text-slate-700"
              >
                {label}

                {required && <span className="text-red-500"> *</span>}

                <input
                  required={required}
                  type={key === "email" ? "email" : "text"}
                  maxLength={max}
                  value={form[key]}
                  onChange={(e) => change(key, e.target.value)}
                  className="mt-2 w-full rounded-xl border border-slate-200 bg-white p-3 font-normal text-slate-900 outline-none focus:border-violet-500"
                />

                {errors[key]?.map((msg, i) => (
                  <span key={i} className="mt-1 block text-xs text-red-600">
                    {msg}
                  </span>
                ))}
              </label>
            ))}
          </div>

          <label className="mt-4 block text-sm font-semibold text-slate-700">
            Status
            <select
              value={form.status}
              onChange={(e) => change("status", e.target.value)}
              className="mt-2 block w-full rounded-xl border border-slate-200 bg-white p-3 text-slate-900 outline-none focus:border-violet-500"
            >
              <option value="ACTIVE">Active</option>

              <option value="INACTIVE">Inactive</option>
            </select>
          </label>

          <label className="mt-4 block text-sm font-semibold text-slate-700">
            Notes
            <textarea
              rows={3}
              maxLength={2000}
              value={form.notes}
              onChange={(e) => change("notes", e.target.value)}
              className="mt-2 block w-full rounded-xl border border-slate-200 bg-white p-3 font-normal text-slate-900 outline-none focus:border-violet-500"
            />
          </label>

          <div className="mt-7 flex justify-end gap-3 border-t border-slate-100 pt-5">
            <button
              type="button"
              disabled={busy}
              onClick={onClose}
              className="rounded-xl bg-slate-100 px-5 py-2.5 font-semibold text-slate-700 disabled:opacity-50"
            >
              Cancel
            </button>

            <button
              type="submit"
              disabled={busy}
              className="inline-flex items-center gap-2 rounded-xl bg-violet-700 px-5 py-2.5 font-semibold text-white hover:bg-violet-800 disabled:opacity-50"
            >
              {busy ? (
                <Loader2 size={17} className="animate-spin" />
              ) : (
                <Save size={17} />
              )}

              {busy
                ? "Saving..."
                : supplier
                  ? "Save Changes"
                  : "Create Supplier"}
            </button>
          </div>
        </form>
      </section>
    </div>,
    document.body,
  );
}
